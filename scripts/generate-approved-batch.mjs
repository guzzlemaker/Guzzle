function day(dateSeed, gameNumber, daily, bonus) {
  return { gameNumber, dateSeed, theme: daily.theme, daily, bonus };
}

function track(theme, entries) {
  return {
    theme: theme.toUpperCase(),
    puzzles: entries.map((entry, index) => {
      const level = index + 1;
      return {
        level,
        category: level === 12 ? 'FINAL LAP' : theme.toUpperCase(),
        clue: normalizeClue(entry.clue),
        answer: normalizeClue(entry.answer),
        difficulty: difficultyFor(level),
        difficultyValue: difficultyValueFor(level),
      };
    }),
  };
}

function p(answer, clue) {
  return { answer, clue };
}

function difficultyFor(level) {
  if (level <= 3) return 'FAST START';
  if (level <= 7) return 'STEADY';
  if (level <= 11) return 'PUSH';
  return 'FINAL LAP';
}

function difficultyValueFor(level) {
  return Math.min(55, 44 + level);
}

function normalizeClue(value) {
  return String(value ?? '').toUpperCase().replace(/\s+/g, ' ').trim();
}

function findAnswerWordLeaks(clue, answer) {
  const answerTokens = normalizeClue(answer)
    .replace(/[^A-Z0-9 ]/g, ' ')
    .split(/\s+/)
    .filter((token) => token.length >= 4 && !ignoredTokens.has(token));

  const clueTokens = new Set(
    normalizeClue(clue)
      .replace(/[^A-Z0-9 ]/g, ' ')
      .split(/\s+/)
      .filter(Boolean),
  );

  return answerTokens.filter((token) => clueTokens.has(token));
}
