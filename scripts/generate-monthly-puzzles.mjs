function addDays(dateString, days) {
  const date = new Date(`${dateString}T00:00:00Z`);
  date.setUTCDate(date.getUTCDate() + days);
  return date.toISOString().slice(0, 10);
}

const difficultyLabels = ['MEDIUM', 'MEDIUM', 'MEDIUM', 'STEADY', 'STEADY', 'HARD', 'HARD', 'HARD', 'EXPERT', 'EXPERT', 'EXPERT', 'FINAL SPRINT'];

const puzzleSets = tracks.map(([theme, answers], trackIndex) => ({
  gameNumber: trackIndex + 1,
  dateSeed: addDays(startDate, trackIndex),
  theme: theme.toUpperCase(),
  puzzles: answers.map((answer, answerIndex) => ({
    level: answerIndex + 1,
    category: answerIndex === answers.length - 1 ? 'FINAL LAP' : theme.toUpperCase(),
    clue: polishedClues[theme]?.[answerIndex] ?? clueTemplates[answerIndex],
    answer,
    difficulty: difficultyLabels[answerIndex],
    difficultyValue: Math.min(60, 50 + answerIndex),
  })),
}));

const dailyDir = path.join('src', 'data', 'daily');
fs.mkdirSync(dailyDir, { recursive: true });

for (const fileName of fs.readdirSync(dailyDir)) {
  if (fileName.endsWith('.json')) {
    fs.unlinkSync(path.join(dailyDir, fileName));
  }
}

for (const puzzleSet of puzzleSets) {
  fs.writeFileSync(
    path.join(dailyDir, `${puzzleSet.dateSeed}.json`),
    `${JSON.stringify(puzzleSet, null, 2)}\n`,
  );
}

const manifest = puzzleSets.map((puzzleSet) => ({
  dateSeed: puzzleSet.dateSeed,
  gameNumber: puzzleSet.gameNumber,
  theme: puzzleSet.theme,
  file: `${puzzleSet.dateSeed}.json`,
}));

fs.writeFileSync(path.join(dailyDir, 'index.json'), `${JSON.stringify(manifest, null, 2)}\n`);
